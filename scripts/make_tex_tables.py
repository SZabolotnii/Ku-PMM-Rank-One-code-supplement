"""Generate the coverage tables (tab:coverage, tab:coverage-s3) as complete tabular blocks.

The file holds the whole tabular, rules included: LaTeX's \\input is not expandable inside an
alignment, so a body-only file would break \\midrule and \\bottomrule.

Bold marks the winning covariance form, produced here and never by hand
(AutoSci academic-writing §6). The winner is the form whose joint coverage is
closest to the nominal 0.95. A difference within two Monte Carlo standard errors
(2 x 0.007 at coverage 0.95 with M = 1000) is noise: if all three forms lie within
that band of the best one, the row has no bold; otherwise every form within the
band of the best one is bold. The rule works on the printed (three-decimal) values,
so ties at printed precision are bolded together.

    .venv/bin/python scripts/make_tex_tables.py           # write paper/tables/*.tex (output/ in the supplement)
    .venv/bin/python scripts/make_tex_tables.py --check   # fail if a file is stale
"""
import argparse
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
# the manuscript repository writes into paper/, the public supplement into output/
OUT = ROOT / ("paper" if (ROOT / "paper").is_dir() else "output") / "tables"

NOMINAL = 0.95
MC_SE = 0.007          # binomial SE of coverage 0.95 with M = 1000, printed in the captions
NOISE = 2 * MC_SE
FORMS = ("closed", "empirical", "naive")
SIZES = (200, 500, 1000, 5000)

TABLES = {
    "coverage_s2.tex": ("k1_sandwich_coverage.csv", ("A0", "A3L", "A2L", "A4L")),
    "coverage_s3.tex": ("k1_sandwich_coverage_s3.csv", ("S300", "S500", "S100", "S075")),
}


def fmt(x, nd=3):
    """Number in the manuscript's style: decimal comma, math mode."""
    s = f"{abs(x):.{nd}f}".replace(".", "{,}")
    return f"${'-' if x < 0 else ''}{s}$"


def fmt_increment(x):
    """Increment label: exact zero prints as 0, otherwise three decimals."""
    return "$0$" if x == 0 else fmt(x)


def bold_mask(values, nominal=NOMINAL, noise=NOISE):
    """True for the forms that win the row; all False when the row is a tie at noise level."""
    printed = [round(v, 3) for v in values]
    dist = [abs(v - nominal) for v in printed]
    best = min(dist)
    if max(dist) - best <= noise + 1e-9:
        return [False] * len(values)
    return [d - best <= noise + 1e-9 for d in dist]


def _read(name):
    with (RESULTS / name).open() as handle:
        return list(csv.DictReader(handle))


def increments():
    """Centering penalty (1 - g_or) R_D per scenario, from the closed-form predictions."""
    return {r["scenario_id"]: float(r["centering_penalty_g"])
            for r in _read("patp_plugin_sandwich_predictions.csv")}


def coverage_body(csv_name, scenarios):
    rows = _read(csv_name)
    inc = increments()
    cov = {(r["scenario_id"], int(r["sample_size"]), r["estimator"]): float(r["coverage_joint_chi2"])
           for r in rows}
    lines = []
    for k, sid in enumerate(scenarios):
        if k:
            lines.append("\\midrule")
        label = f"{sid} (приріст {fmt_increment(round(inc[sid], 3))})"
        for j, n in enumerate(SIZES):
            values = [cov[(sid, n, f)] for f in FORMS]
            cells = [fmt(v) for v in values]
            cells = [f"$\\mathbf{{{c[1:-1]}}}$" if b else c for c, b in zip(cells, bold_mask(values))]
            head = label if j == 0 else ""
            lines.append(f"{head:<24} & ${n}$ & " + " & ".join(cells) + " \\\\")
    head = ["% Generated by scripts/make_tex_tables.py from results/" + csv_name + " - do not edit.",
            "\\begin{tabular}{llccc}", "\\toprule",
            "Режим & $n$ & замкнена \\eqref{eq:sigmahat} & емпірична \\eqref{eq:sigmaemp} & наївна \\\\",
            "\\midrule"]
    tail = ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(head + lines + tail) + "\n"


def build():
    return {name: coverage_body(*spec) for name, spec in TABLES.items()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if any generated file is stale")
    args = ap.parse_args()
    stale = []
    for name, text in build().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            OUT.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("stale: " + ", ".join(stale) + " - run scripts/make_tex_tables.py")
        sys.exit(1)


if __name__ == "__main__":
    main()
